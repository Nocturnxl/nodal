// Writes THIRD-PARTY-NOTICES.md: the licence of every package that ships in the
// installer. That is (a) the runtime dependency tree copied into the app and
// (b) the packages the bundler compiled into the renderer, which the build
// records in out/.bundled-packages.json. Run after `npm run bundle`.
import { execSync } from 'node:child_process';
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, resolve, sep } from 'node:path';

const root = resolve(import.meta.dirname, '..');
const bundledFile = join(root, 'out/.bundled-packages.json');
if (!existsSync(bundledFile)) {
  console.error('out/.bundled-packages.json is missing. Run "npm run bundle" first.');
  process.exit(2);
}

const dirs = new Set();
// (a) production tree
const ls = execSync('npm ls --omit=dev --all --parseable', { cwd: root, encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] });
for (const line of ls.split(/\r?\n/)) if (line.includes(`${sep}node_modules${sep}`)) dirs.add(line.trim());
// (b) bundled into the renderer
for (const rel of JSON.parse(readFileSync(bundledFile, 'utf8'))) dirs.add(join(root, rel));
// The shell itself
dirs.add(join(root, 'node_modules/electron'));

const entries = new Map();
for (const dir of dirs) {
  const pkgFile = join(dir, 'package.json');
  if (!existsSync(pkgFile)) continue;
  const pkg = JSON.parse(readFileSync(pkgFile, 'utf8'));
  if (!pkg.name || !pkg.version) continue;
  const licence = typeof pkg.license === 'string' ? pkg.license : (pkg.license?.type ?? (Array.isArray(pkg.licenses) ? pkg.licenses.map((l) => l.type).join(' OR ') : 'UNKNOWN'));
  const file = readdirSync(dir).find((f) => /^(licen[cs]e|copying)(\.|$)/i.test(f));
  const text = file ? readFileSync(join(dir, file), 'utf8').replace(/\r\n/g, '\n').trim() : '';
  const repo = typeof pkg.repository === 'string' ? pkg.repository : (pkg.repository?.url ?? '');
  entries.set(`${pkg.name}@${pkg.version}`, { name: pkg.name, version: pkg.version, licence, text, repo: repo.replace(/^git\+/, '').replace(/\.git$/, '') });
}

const list = [...entries.values()].sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version));
const counts = {};
for (const e of list) counts[e.licence] = (counts[e.licence] ?? 0) + 1;

const out = [
  '# Third-party notices',
  '',
  `NODAL includes the ${list.length} open-source packages listed below. This file is generated by \`npm run notices\`; do not edit it by hand.`,
  '',
  'Electron also bundles Chromium and Node.js. Their notices ship with the app as `LICENSES.chromium.html` and `LICENSE` next to the executable.',
  '',
  '## Licences in use',
  '',
  '| Licence | Packages |',
  '| --- | ---: |',
  ...Object.entries(counts)
    .sort((a, b) => b[1] - a[1])
    .map(([l, n]) => `| ${l} | ${n} |`),
  '',
  '## Packages',
  '',
];
for (const e of list) {
  out.push(`### ${e.name} ${e.version}`, '', `Licence: ${e.licence}${e.repo ? `. Source: ${e.repo}` : ''}`, '');
  if (e.text) out.push('```text', e.text.replace(/```/g, "'''"), '```', '');
  else out.push('No licence file is included in the package; see the source repository.', '');
}
writeFileSync(join(root, 'THIRD-PARTY-NOTICES.md'), out.join('\n'), 'utf8');

const review = list.filter((e) => !/^(MIT|ISC|BSD-2-Clause|BSD-3-Clause|Apache-2\.0|0BSD|BlueOak-1\.0\.0|CC0-1\.0|Unlicense|Python-2\.0|\(MIT OR Apache-2\.0\)|MIT OR Apache-2\.0|\(MIT OR CC0-1\.0\)|CC-BY-4\.0)$/.test(e.licence));
console.log(`${list.length} packages. Licences: ${Object.entries(counts).map(([l, n]) => `${l} ${n}`).join(', ')}`);
if (review.length) console.log(`Needs a human look (not a common permissive licence): ${review.map((e) => `${e.name}@${e.version} [${e.licence}]`).join(', ')}`);
